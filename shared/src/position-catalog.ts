export function matchesPositionCatalogEntry(entry: PositionCatalogEntry, query: string) {
  const keyword = query.trim().toLocaleLowerCase();
  return !keyword
    || entry.code.toLocaleLowerCase().includes(keyword)
    || entry.name.toLocaleLowerCase().includes(keyword);
}

export function searchPositionCatalog(query: string) {
  return POSITION_CATALOG.filter((entry) => matchesPositionCatalogEntry(entry, query));
}
